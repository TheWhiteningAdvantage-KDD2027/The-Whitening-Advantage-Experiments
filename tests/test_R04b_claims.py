def test_R04b_gamma_target_is_attainable_and_realised():
    """
    The defect R04 found: solve_beta_for_gamma(alpha, target) called with its
    arguments transposed returns beta = 0 and the campaign runs at Gamma = 1.105
    whatever the label. Reimplemented here from the closed form alone, the
    documented order must hit 11.58.
    """
    lo, hi = 0.0, 1.0 - ALPHA_GARCH - 1e-6
    for _ in range(100):
        mid = (lo + hi) / 2.0
        if compute_gamma_exact(ALPHA_GARCH, mid) < GAMMA_RACE:
            lo = mid
        else:
            hi = mid
    assert abs(compute_gamma_exact(ALPHA_GARCH, mid) - GAMMA_RACE) < 1e-6
    assert compute_gamma_exact(ALPHA_GARCH, 0.0) == pytest.approx(1.105263, abs=1e-6)


