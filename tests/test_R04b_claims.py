"""
R04b -- resolution of the efficiency crossing point. Acceptance and reporting.

Two kinds of statement live in this file and they are kept apart deliberately.

*Blocking assertions* rest on deterministic relations -- cardinalities, a
calibration that converged, an analytic identity, the arithmetic of a bracket --
or on omnibus statistics whose family-wise firing probability under their own
null is at most 1%. None of them is a per-cell hypothesis test on a draw, which
preamble S4bis forbids for a family of this size.

*Reporting output* prints this campaign against the values v87 publishes and
asserts nothing about the comparison. A gate on reproducing 4.9, 4.6 or 0.3
would make the manuscript the criterion rather than the object of study; R04
already classifies those three as falsified, and R04b exists to locate what
replaces them, not to decide in advance what it will find.

No numeric literal here comes from R04b's own output. The constants admitted are
those printed in v87 -- 2,000 null streams, a 5,000-step horizon, a 500-step
warm-up, a 5% target with a bisection tolerance of 0.003 over 15 iterations,
Gamma = 11.58, c = 0.5, the crossings 4.9 and 4.6, the analytic 4.7, the
estimation cost 0.3, the Gaussian ceiling pi/2 -- the nu grid of the R04b prompt,
and the 8.52 that AUDIT_R04.md interpolated across the empty (7, 30) interval.
Every value of R04 is read from its CSV by the code with
float_precision='round_trip' on both sides.

Where a test compares the emitted macros against the CSV, the rule that produced
them is reimplemented here rather than imported, so the test is a comparison of
two implementations and not a restatement of one.
"""

