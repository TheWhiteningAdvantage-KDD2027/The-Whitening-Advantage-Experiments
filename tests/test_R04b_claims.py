# --- INDEPENDENT REIMPLEMENTATIONS OF THE DERIVED RULES ---

def compute_gamma_exact(alpha, beta):
    phi = alpha + beta
    denom = 1.0 - 2.0 * alpha * beta - beta ** 2
    rho1 = alpha * (1.0 - beta * phi) / denom
    return max(1.0, 1.0 + 2.0 * rho1 / (1.0 - phi))


def shape_prediction(nu):
    """1/(4 f_z(0)^2) for a Student-t scaled to unit variance."""
    f0 = stats.t.pdf(0.0, df=nu) / math.sqrt((nu - 2.0) / nu)
    return 1.0 / (4.0 * f0 ** 2)


def crossing_point(nu_values, ratios):
    """Linear interpolation of the first upward crossing of unity."""
    order = np.argsort(np.asarray(nu_values, dtype=float))
    nu = np.asarray(nu_values, dtype=float)[order]
    r = np.asarray(ratios, dtype=float)[order]
    for i in range(len(nu) - 1):
        if r[i] < 1.0 <= r[i + 1]:
            return nu[i] + (nu[i + 1] - nu[i]) * (1.0 - r[i]) / (r[i + 1] - r[i]), nu[i], nu[i + 1]
    return float('nan'), float('nan'), float('nan')


def inferential_bracket(nu_values, ratios, ses):
    """
    Last point before the crossing whose interval is entirely below unity, and
    first whose interval is entirely above it. The right edge is taken first so
    the pair is ordered by construction.
    """
    nu = np.asarray(nu_values, dtype=float)
    lo = np.asarray(ratios) - Z_95 * np.asarray(ses)
    hi = np.asarray(ratios) + Z_95 * np.asarray(ses)
    above = nu[lo > 1.0]
    right = float(above.min()) if len(above) else float('nan')
    eligible = nu < right if np.isfinite(right) else np.ones(len(nu), dtype=bool)
    below = nu[eligible & (hi < 1.0)]
    return (float(below.max()) if len(below) else float('nan')), right


def curve(df, arm):
    """The crossing curve of one arm, ordered in nu: (nu, ratio, standard error)."""
    block = df[df['arm'] == arm].sort_values('nu')
    return (block['nu'].to_numpy(dtype=float),
            block['ratio_concept_to_arm'].to_numpy(dtype=float),
            block['ratio_concept_to_arm_se'].to_numpy(dtype=float))


