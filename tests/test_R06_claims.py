def test_R06_squared_stream_rejects_massively(grid, macros):
    """Reported with its value, with no assertion on any extremum, as the prompt requires."""
    p = float((grid['p_data'] < ALPHA_LB).mean())
    print(f"[R06] pooled squared-stream rejection {p:.4%}")
    assert float(macros["RSixPooledDataReject"].rstrip("\\%")) == pytest.approx(round(p * 100, 2))
    assert p > 0.5, "The squared stream is the arm the penalty is supposed to break"


def test_R06_task_boundaries_saturate(task, macros):
    """
    The literal claim of v87: rejection 100% for c >= 0.5 and for MSE. Blocking,
    because a rate of 100% over 100 streams cannot fall through sampling noise
    without the effect itself having changed. Part B is NOT pooled: each cell is
    a marginal statement over 100 independent seeds, so the design effect of
    panel A does not apply here.
    """
    for task_type, c in SATURATED_CELLS:
        observed = rate(task, 'p_val', task_type=task_type, c=c)
        assert observed == 1.0, f"{task_type} c={c} rejects at {observed:.2f}, not 1.00"
    assert float(macros["RSixBinaryRejectCHalf"].rstrip("\\%")) == 100
    assert float(macros["RSixContinuousReject"].rstrip("\\%")) == 100
    for _, block in task.groupby(['task_type', 'c']):
        assert block['seed'].nunique() == N_SEEDS


def test_R06_intermediate_threshold_is_reported_and_labelled(task, macros):
    """
    binary c = 0.25 is not cited anywhere in v87. It is kept because it is the
    only measurement of the transition between the white regime and the saturated
    one in this repository, and it must sit strictly between them.
    """
    intermediate = rate(task, 'p_val', task_type='binary', c=0.25)
    median = rate(task, 'p_val', task_type='binary', c=0.0)
    print(f"[R06] transition: c=0 {median:.2f}, c=0.25 {intermediate:.2f} (not cited in v87), "
          f"c=0.5 {rate(task, 'p_val', task_type='binary', c=0.5):.2f}")
    assert median < intermediate < 1.0
    assert float(macros["RSixBinaryRejectCQuarter"].rstrip("\\%")) == pytest.approx(round(intermediate * 100))


def test_R06_median_task_control_covers_nominal_and_is_weakly_resolved(task, macros):
    """
    The control that certifies the median task, and the resolution it actually
    has. At N = 100 the half-width is of the order of the level being tested, so
    the control is consistent with whiteness rather than a confirmation of it,
    and the R06 prompt requires that said rather than masked.
    """
    k = int((task[(task['task_type'] == 'binary') & np.isclose(task['c'], 0.0)]['p_val'] < ALPHA_LB).sum())
    low, high = wilson(k, N_SEEDS)
    half_width = (high - low) / 2
    print(f"[R06] median-task control {k}/{N_SEEDS}, Wilson [{low:.4%}, {high:.4%}], "
          f"half-width {half_width:.2%} = {half_width / ALPHA_LB:.1f} times the nominal level")
    assert low <= ALPHA_LB <= high
    assert float(macros["RSixMedianControlHalfWidth"]) == pytest.approx(round(half_width * 100, 1))
    assert half_width > ALPHA_LB / 2, (
        "This assertion exists to keep the weakness stated: if it ever fails, the control has become "
        "sharp enough to confirm rather than merely to be consistent, and the prose must be revised")


# --- HYGIENE AND WITNESS IDENTITY ---

def test_R06_no_silent_fallback_survived_into_the_artefacts(grid, task, independent):
    """
    The submitted script mapped a degenerate stream to p = 1.0 and any exception
    to NaN, both of which count as a non-rejection and both of which therefore
    push the measured rate towards white. Neither may appear in an artefact.
    """
    for frame, column in ((grid, 'p_concept'), (grid, 'p_data'),
                          (task, 'p_val'), (independent, 'p_concept')):
        assert frame[column].notna().all(), f"{column} carries NaN, the value the bare except returned"
        assert (frame[column] != 1.0).all(), f"{column} carries an exact 1.0, the degenerate-stream value"
        assert frame[column].between(0.0, 1.0).all()


def test_R06_reproduces_the_witness_byte_for_byte(grid, task, witness_grid, witness_task):
    """
    This experiment is a port: the generator and both task evaluators are the
    submitted ones, asserted byte-identical at run time. The strongest available
    consequence is that the regenerated tables equal the witness cell for cell.

    It is asserted here because for THIS experiment the witness is not a target
    but a definition: the campaign was re-run with the same code and the same
    seeds, so any difference would be an environment defect rather than a
    legitimate correction. Where a correction does move a value -- the
    fourth-moment boundary, which is now computed -- the comparison is reported
    and not gated.
    """
    for mine, theirs in ((grid, witness_grid), (task, witness_task)):
        assert list(mine.columns) == list(theirs.columns)
        assert len(mine) == len(theirs)
    pd.testing.assert_frame_equal(grid, witness_grid, check_exact=True)
    pd.testing.assert_frame_equal(task, witness_task, check_exact=True)


