# --- INDEPENDENT REIMPLEMENTATIONS OF THE DERIVED RULES ---

def wilson(k, n, z=Z_95):
    p = k / n
    den = 1.0 + z * z / n
    centre = (p + z * z / (2.0 * n)) / den
    half = z * math.sqrt(p * (1.0 - p) / n + z * z / (4.0 * n * n)) / den
    return max(0.0, centre - half), min(1.0, centre + half)


def kish_design_effect(matrix):
    """Cluster-robust variance of the pooled rate over the simple-random-sample one."""
    n_clusters = matrix.shape[0]
    p = matrix.mean()
    se_cluster = np.std(matrix.mean(axis=1), ddof=1) / math.sqrt(n_clusters)
    se_srs = math.sqrt(p * (1.0 - p) / matrix.size)
    return (se_cluster / se_srs) ** 2


def gamma_closed_form(alpha, beta):
    """
    The penalty in closed form. The guard at the pole is not decoration: the
    denominator 1 - 2*alpha*beta - beta^2 vanishes at beta = sqrt(alpha^2+1) -
    alpha, and past it the expression returns a finite negative number that would
    let a root finder converge on a Gamma that does not exist.
    """
    if alpha == 0.0 and beta == 0.0:
        return 1.0
    phi = alpha + beta
    denom = 1.0 - 2.0 * alpha * beta - beta ** 2
    if denom <= 0.0 or phi >= 1.0:
        return float('inf')
    return 1.0 + 2.0 * (alpha * (1.0 - beta * phi) / denom) / (1.0 - phi)


def matrix_of(df, column):
    frame = df.assign(_r=(df[column] < ALPHA_LB).astype(int))
    index = 'stream' if 'stream' in df.columns else 'seed'
    return frame.pivot(index=index, columns='gamma', values='_r').to_numpy()


def rate(df, column, **selector):
    block = df
    for key, value in selector.items():
        block = block[np.isclose(block[key], value)] if isinstance(value, float) else block[block[key] == value]
    return float((block[column] < ALPHA_LB).mean())


