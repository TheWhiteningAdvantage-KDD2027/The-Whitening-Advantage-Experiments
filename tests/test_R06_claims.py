"""
R06 -- empirical validity map of the whitening property. Acceptance and reporting.

Two kinds of statement live in this file and they are kept apart deliberately.

*Blocking assertions* rest on deterministic relations -- cardinalities, a realised
penalty, an analytic identity, the arithmetic of an interval -- or on pooled
statistics computed with the variance the experimental design imposes. There is
no per-cell gate on the 13 Gamma: that family fires at least once with
probability 1 - 0.95^13 = 49% under its own null, which preamble S4bis forbids,
and the submitted script gated exactly there.

*Reporting output* prints this campaign against the witness and asserts nothing
about the comparison.

No numeric literal here comes from R06's own output. The constants admitted are
those printed in v87 and in the R06 prompt -- 100 streams per configuration, an
8,000-step horizon, Ljung-Box at lag 20, a 5% nominal level, nu = 7, the 13-point
Gamma grid, the four thresholds, 100% rejection for c >= 0.5 and for MSE, the
fourth-moment boundary printed as 41.6 -- and every reference value is read from
the vendored witness by the code with float_precision='round_trip'.

The three derived rules of this experiment -- the Wilson interval, the Kish
design effect, and the fourth-moment boundary -- are reimplemented here
independently of the experiment module, so that a test of any of them is a
comparison of two implementations and not a restatement of one.
"""

