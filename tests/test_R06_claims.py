def test_R06_gamma_grid_is_realised_in_closed_form():
    """
    The argument order of solve_beta_for_gamma is the point audited by the R06
    prompt: a transposed call of exactly this shape ran another stream at a single
    penalty without any output revealing it. Reimplemented here from the closed
    form alone, the documented order must attain every target.
    """
    for target in GAMMA_GRID:
        if target == 1:
            assert gamma_closed_form(0.0, 0.0) == 1.0
            continue
        pole = math.sqrt(ALPHA_FIXED ** 2 + 1.0) - ALPHA_FIXED
        beta = root_scalar(lambda b: gamma_closed_form(ALPHA_FIXED, b) - target,
                           bracket=[0.0, pole - 1e-6], method='brentq').root
        assert abs(gamma_closed_form(ALPHA_FIXED, beta) - target) < 1e-6


def test_R06_fourth_moment_boundary_is_computed_not_hard_coded(macros):
    """
    The boundary must follow (alpha, nu). The submitted script carried the
    kurtosis as a default argument `5.0` whose value happens to be right for
    nu = 7; a literal cannot follow nu, so it is recomputed here from
    3(nu-2)/(nu-4) and compared to the emitted macro.
    """
    kurtosis = 3.0 * (NU_INNOVATION - 2.0) / (NU_INNOVATION - 4.0)
    assert kurtosis == pytest.approx(5.0)
    beta_star = root_scalar(
        lambda b: kurtosis * ALPHA_FIXED ** 2 + 2 * ALPHA_FIXED * b + b ** 2 - 1.0,
        bracket=[0.0, 1.0 - ALPHA_FIXED]).root
    gamma_star = gamma_closed_form(ALPHA_FIXED, beta_star)
    assert float(macros["RSixFourthMomentGamma"]) == pytest.approx(round(gamma_star, 2))
    assert float(macros["RSixFourthMomentBeta"]) == pytest.approx(round(beta_star, 4))
    # v87 prints 41.6; the computed boundary must round to it at that precision.
    assert round(gamma_star, 1) == FOURTH_MOMENT_GAMMA_PUBLISHED


def test_R06_boundary_is_not_confused_with_the_nearest_grid_point(grid, macros):
    """
    The grid carries 41 and the analytic boundary is 41.58. They are different
    quantities and the figure of the submitted campaign put an axis tick at the
    boundary with a marker at 41 on top of it. The macros must keep them apart.
    """
    gamma_star = float(macros["RSixFourthMomentGamma"])
    nearest = float(macros["RSixNearestGridPoint"])
    assert nearest in set(float(g) for g in GAMMA_GRID)
    assert gamma_star not in set(float(g) for g in GAMMA_GRID)
    assert nearest < gamma_star, "The grid brackets the boundary from below"


# --- (b) THE LEVEL OF THE BINARY STREAM, POOLED, WITH THE DESIGN VARIANCE ---

def test_R06_panel_A_design_is_paired_and_declared(grid, macros):
    """
    One seed carries the same label stream to every Gamma, because the
    innovations are drawn before the variance recursion. The error stream is NOT
    shared -- the classifier reads amplitudes -- so the readings are correlated
    rather than identical, and the design effect is what quantifies that.
    """
    assert grid['p_concept'].nunique() == len(grid), (
        "Every reading must be distinct; identical readings would mean the error stream, "
        "and not merely the label stream, is shared across Gamma")
    assert int((grid.groupby('seed')['p_concept'].nunique() == 1).sum()) == 0
    deff = kish_design_effect(matrix_of(grid, 'p_concept'))
    assert float(macros["RSixDesignEffect"]) == pytest.approx(round(deff, 2))
    assert deff > 1.0, "A paired design cannot carry less correlation than an independent one"
    assert float(macros["RSixEffectiveStreams"]) == pytest.approx(round(len(grid) / deff))


def test_R06_pooled_binary_level_covers_nominal_at_cluster_precision(grid, macros):
    """
    The blocking statement of panel A. The interval must carry the design
    effect: an interval that assumes 1300 independent streams understates its
    half-width by the square root of it, which is the correction the R06 prompt
    itself was amended to require.
    """
    matrix = matrix_of(grid, 'p_concept')
    deff = kish_design_effect(matrix)
    p = float(matrix.mean())
    half = Z_95 * math.sqrt(deff * p * (1.0 - p) / matrix.size)
    low, high = p - half, p + half
    k = int(matrix.sum())
    naive_low, naive_high = wilson(k, matrix.size)
    print(f"[R06] pooled binary rejection {p:.4%}; cluster-robust [{low:.4%}, {high:.4%}], "
          f"naive Wilson [{naive_low:.4%}, {naive_high:.4%}], design effect {deff:.2f}")
    assert low <= ALPHA_LB <= high, (
        f"The pooled binary rejection rate {p:.4%} excludes the nominal level at cluster-robust "
        f"precision: the binary error stream would not be white across the Gamma grid")
    assert (high - low) > (naive_high - naive_low), (
        "The cluster-robust interval must be wider than the one that assumes independence")
    assert float(macros["RSixPooledConceptReject"].rstrip("\\%")) == pytest.approx(round(p * 100, 2))


def test_R06_counterfactual_arm_removes_the_pairing(independent, grid):
    """
    The design effect measured two ways: estimated from the paired campaign, and
    obtained by removing the pairing. An arm keyed per (Gamma, stream) has no
    shared label streams, so its design effect must sit at unity while the paired
    one sits well above it, and its level must still cover nominal.
    """
    deff_paired = kish_design_effect(matrix_of(grid, 'p_concept'))
    deff_independent = kish_design_effect(matrix_of(independent, 'p_concept'))
    print(f"[R06] design effect: paired {deff_paired:.2f}, independent seeds {deff_independent:.2f}")
    assert deff_independent < deff_paired
    assert deff_independent == pytest.approx(1.0, abs=0.5)
    assert independent['seed'].nunique() == len(independent), "Every counterfactual cell has its own seed"
    matrix = matrix_of(independent, 'p_concept')
    low, high = wilson(int(matrix.sum()), matrix.size)
    assert low <= ALPHA_LB <= high, (
        "Under independent label streams, where the pairing can mask nothing, the binary stream "
        "must still hold the nominal level")


def test_R06_no_per_gamma_gate_is_possible(grid):
    """
    Records why the 13 per-cell gates of the submitted script are inadmissible,
    and asserts only the arithmetic of that statement, never the outcome.
    """
    family_wise = 1.0 - 0.95 ** len(GAMMA_GRID)
    print(f"[R06] a per-Gamma family of {len(GAMMA_GRID)} 95% intervals fires at least once with "
          f"probability {family_wise:.4f} under its own null")
    assert family_wise > 0.05, "S4bis applies precisely because this probability exceeds 5%"
    covered = sum(1 for _, block in grid.groupby('gamma')
                  if (lambda ci: ci[0] <= ALPHA_LB <= ci[1])(
                      wilson(int((block['p_concept'] < ALPHA_LB).sum()), N_SEEDS)))
    print(f"[R06] {covered} of {len(GAMMA_GRID)} per-Gamma intervals cover the nominal level "
          f"(descriptive, not a criterion)")


