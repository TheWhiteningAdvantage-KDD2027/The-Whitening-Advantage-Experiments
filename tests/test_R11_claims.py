    """
    S1.2 of the plan: under common random numbers the twenty grid estimates share
    their draws, so the analytic OLS standard error does not hold and every
    p-value comes from a seed-cluster bootstrap. Both errors are persisted and
    their ratio -- which IS the design effect -- is a column.
    """
    fitted = slopes[np.isfinite(slopes["slope"])]
    assert len(fitted) > 0
    assert fitted["se_bootstrap"].notna().all()
    assert fitted["se_ols"].notna().all()
    ratios = (fitted["se_bootstrap"] / fitted["se_ols"]).to_numpy(dtype=float)
    assert np.isfinite(ratios).any()
    finite_p = slopes["p_value"].to_numpy(dtype=float)
    finite_p = finite_p[np.isfinite(finite_p)]
    assert ((finite_p >= 0.0) & (finite_p <= 1.0)).all()
    assert np.allclose(fitted["se_ratio"].to_numpy(dtype=float), ratios, equal_nan=True)


