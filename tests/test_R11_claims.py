# --- THE DEGENERACY OF THE COMMON-RANDOM-NUMBERS H0 ARM ---

def test_R11_crn_h0_arm_is_degenerate_and_the_independent_arm_is_not(concept_fpr,
                                                                     concept_fpr_indep):
    """
    `simulate_garch11` draws its innovations before the variance recursion, so
    eps[t] = sqrt(sigma2[t]) * z[t] with sigma2[t] > 0 and sign(eps_t) =
    sign(z_t) exactly. Under a seed keyed on role and index alone the H0 binary
    stream is therefore identical at every Gamma, and the CRN table must carry
    one number repeated N_GAMMA times. That is why it supports no claim.
    """
    for arm in ("reset", "warmstart"):
        block = arm_of(concept_fpr, arm)
        for det in DETECTORS_CONCEPT:
            assert block[f"FPR_{det}"].nunique() == 1, (
                f"The CRN H0 arm must be degenerate in Gamma for {det}: the penalty leaves no "
                f"trace on the sign of the innovation")
    varying = sum(1 for det in DETECTORS_CONCEPT if concept_fpr_indep[f"FPR_{det}"].nunique() > 1)
    assert varying >= 3, (
        "Breaking the pairing must make the measurement vary across Gamma; if it does not, the "
        "independent arm is not independent")


def test_R11_kish_design_effect_of_a_degenerate_grid_is_its_width(concept_fpr):
    """
    A grid whose readings are identical within a seed carries a design effect
    equal to the number of grid points, so its N_GAMMA x n_seeds streams hold the
    information of n_seeds. Verified on the arithmetic rather than asserted: with
    every column equal, the cluster-robust variance of the pooled rate is the
    variance of a single column.
    """
    block = arm_of(concept_fpr, "reset")
    n_seeds = int(block["n_seeds"].iloc[0])
    for det in ("CUSUM", "DDM"):
        p = float(block[f"FPR_{det}"].iloc[0])
        if p <= 0.0 or p >= 1.0:
            continue
        se_cluster = math.sqrt(p * (1.0 - p) / n_seeds)
        se_srs = math.sqrt(p * (1.0 - p) / (n_seeds * N_GAMMA))
        assert (se_cluster / se_srs) ** 2 == pytest.approx(float(N_GAMMA), rel=1e-9)
    assert int(block["n_eff"].iloc[0]) == n_seeds, (
        "The CRN arm must declare an effective sample size of n_seeds, not N_GAMMA x n_seeds")


# --- INTERVALS: THE sqrt(2) INFLATION AND THE CLAMP ---

def test_R11_pht_intervals_carry_the_calibration_variance_factor(pht_fpr):
    """
    C5. The PHT threshold is estimated on 2,000 i.i.d. streams and read on 5,000
    fresh ones, so the held-out level carries the binomial variance twice over
    (docs/DEVIATIONS.md entry 16, measured at 1.4133 against sqrt(2) = 1.4142).
    Inverting the score test at a doubled variance is the Wilson interval at
    z * sqrt(2), and the persisted bounds must be exactly that -- and therefore
    strictly wider than the uninflated interval wherever the rate is interior.
    """
    n = int(pht_fpr["n_seeds"].iloc[0])
    checked = 0
    for _, row in pht_fpr.iterrows():
        for label in ("raw", "sqrt", "gamma"):
            p = float(row[f"FPR_{label}"])
            low, high = wilson(p, n, z=Z_95 * SQRT_TWO)
            assert float(row[f"FPR_{label}_low"]) == pytest.approx(low, abs=1e-12)
            assert float(row[f"FPR_{label}_high"]) == pytest.approx(high, abs=1e-12)
            if 0.0 < p < 1.0:
                plain_low, plain_high = wilson(p, n)
                assert (high - low) > (plain_high - plain_low)
                checked += 1
    assert checked > 0, "No interior rate: the inflation would be untested"


def test_R11_every_interval_bound_is_clamped(pht_fpr, concept_fpr, concept_fpr_indep, magnitude):
    """Boundary constraint: every interval bound is clipped to [0, 1] before persistence."""
    for frame in (pht_fpr, concept_fpr, concept_fpr_indep, magnitude):
        for column in frame.columns:
            if column.endswith("_low") or column.endswith("_high"):
                values = frame[column].to_numpy(dtype=float)
                finite = values[np.isfinite(values)]
                assert (finite >= 0.0).all() and (finite <= 1.0).all(), f"{column} escapes [0, 1]"


# --- SLOPES, DOMAINS AND THE SENSITIVITY ARM ---

def test_R11_data_loglog_slopes_reproduce_by_an_independent_fit(data_add, slopes, macros):
    """
    The three published log-log slopes appear in no CSV, no log and no script of
    the submitted campaign. R11 emits them as macros computed in memory; this
    test refits them from the persisted table with an independent OLS and
    requires the two to agree, and it requires the fitted domain to be exactly
    the points the censoring rule admits.
    """
    block = arm_of(data_add, "as_submitted")
    x = np.log(block["Gamma"].to_numpy(dtype=float))
    for det in DETECTORS_DATA:
        add = block[f"ADD_{det}"].to_numpy(dtype=float)
        rate = block[f"DetRate_{det}"].to_numpy(dtype=float)
        mask = np.isfinite(add) & (rate >= CENSORING_DETRATE) & (add > 0)
        y = np.where(mask, np.log(np.where(mask, add, 1.0)), np.nan)
        slope, n_points = ols_slope(x, y)
        # `domain` alone is ambiguous: the linear traceability fit carries the
        # same domain string, so the response must be named as well.
        row = slopes[(slopes["pipeline"] == "Data") & (slopes["detector"] == det)
                     & (slopes["arm"] == "as_submitted")
                     & (slopes["response"] == LOGLOG_RESPONSE)
                     & (slopes["domain"] == "DetRate >= 0.5")]
        assert len(row) == 1
        assert float(row["slope"].iloc[0]) == pytest.approx(slope, rel=1e-9)
        assert int(row["n_points"].iloc[0]) == n_points == int(mask.sum())
        camel = {"CUSUM": "Cusum", "PHT": "Pht", "ADWIN": "Adwin"}[det]
        assert float(macros[f"RElevenDataSlope{camel}"]) == pytest.approx(round(slope, 2))
        print(f"[R11] Data log-log slope {det}: {slope:.4f} on {n_points} of {N_GAMMA} points "
              f"(v87 prints {PUBLISHED_DATA_LOGLOG_SLOPE[det]})")


