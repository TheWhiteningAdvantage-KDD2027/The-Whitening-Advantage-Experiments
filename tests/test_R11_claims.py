def test_R11_gamma_grid_is_the_target_grid_and_its_floor_is_respected(concept_add):
    """
    The R11 prompt lists the grid as the literals 1.17, 6.44, 11.89, ...; those
    are the submitted campaign's REALISED penalties rounded to two decimals, and
    the targets that produce them are concat(linspace(1,50,10), linspace(60,200,10)).
    Both halves of that statement are checked here from the closed form alone.
    """
    floor = attainable_floor(ALPHA_FIXED)
    assert floor == pytest.approx(gamma_closed_form(ALPHA_FIXED, 0.0), rel=1e-15)
    realised = []
    for target in GAMMA_TARGETS:
        beta = solve_beta(ALPHA_FIXED, target)
        got = gamma_closed_form(ALPHA_FIXED, beta)
        if target >= floor:
            # Attainable: the bisection must find the root. 100 halvings reach
            # 2^-100, far inside this tolerance, which therefore tests the
            # solver and is not derived from any observed deviation.
            assert abs(got / target - 1.0) < 1e-6
        else:
            # Unattainable: no root exists, so the exact assertion applies.
            assert beta == 0.0
            assert got == pytest.approx(floor, rel=1e-15)
        realised.append(got)
    assert tuple(round(g, 2) for g in realised) == GAMMA_PRINTED_LITERALS, (
        "The printed literals of the prompt must be the realised penalties of the target grid")
    # Exactly one target of the twenty lies below the attainable floor.
    assert sum(1 for t in GAMMA_TARGETS if t < floor) == 1
    # The persisted grid is the realised penalty, not the target.
    block = arm_of(concept_add, "as_submitted")
    assert np.allclose(block["Gamma"].to_numpy(dtype=float), realised, rtol=1e-12)
    assert np.allclose(block["Gamma_realised"].to_numpy(dtype=float), realised, rtol=1e-12)
    assert int((~block["attainable"].astype(bool)).sum()) == 1


