# --- INDEPENDENT REIMPLEMENTATIONS OF THE DERIVED RULES ---

def wilson(p, n, z=Z_95):
    """Wilson score interval, written from the score-test inversion."""
    den = 1.0 + z * z / n
    centre = (p + z * z / (2.0 * n)) / den
    half = z * math.sqrt(p * (1.0 - p) / n + z * z / (4.0 * n * n)) / den
    return max(0.0, centre - half), min(1.0, centre + half)


def gamma_closed_form(alpha, beta):
    """
    The penalty in closed form. The guard at the pole is not decoration: the
    denominator 1 - 2*alpha*beta - beta^2 vanishes at beta = sqrt(alpha^2+1) -
    alpha, and past it the expression returns a finite value that would let a
    root finder converge on a penalty that does not exist.
    """
    phi = alpha + beta
    if phi >= 1.0:
        return float('inf')
    denom = 1.0 - 2.0 * alpha * beta - beta ** 2
    if denom <= 0.0:
        return (1.0 + phi) / (1.0 - phi)
    return max(1.0, 1.0 + 2.0 * (alpha * (1.0 - beta * phi) / denom) / (1.0 - phi))


def attainable_floor(alpha):
    """
    The infimum of the penalty at fixed alpha, reached at beta = 0 where
    denom = 1, rho1 = alpha and phi = alpha, so Gamma = 1 + 2*alpha/(1 - alpha).
    Written from that one-line derivation rather than by calling the closed form.
    """
    return 1.0 + 2.0 * alpha / (1.0 - alpha)


def solve_beta(alpha, target, iterations=100):
    """Bisection on [0, 1 - alpha - 1e-6], the submitted solver's own bracket."""
    if target <= 1.0:
        return 0.0
    lo, hi = 0.0, 1.0 - alpha - 1e-6
    mid = lo
    for _ in range(iterations):
        mid = (lo + hi) / 2.0
        if gamma_closed_form(alpha, mid) < target:
            lo = mid
        else:
            hi = mid
    return mid


def ols_slope(x, y):
    """OLS slope from the normal equations, not from a library regression."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    x, y = x[ok], y[ok]
    if len(x) < 3:
        return float('nan'), 0
    xbar, ybar = x.mean(), y.mean()
    return float(((x - xbar) * (y - ybar)).sum() / ((x - xbar) ** 2).sum()), len(x)


def peak_to_peak(values):
    ok = np.asarray(values, dtype=float)
    ok = ok[np.isfinite(ok)]
    if len(ok) < 2 or ok.mean() == 0.0:
        return float('nan')
    return float((ok.max() - ok.min()) / ok.mean())


