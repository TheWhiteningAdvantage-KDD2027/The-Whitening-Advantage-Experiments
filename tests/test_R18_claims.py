def test_R18_the_ljung_box_rejection_of_both_arms_covers_the_nominal_level(applied):
    """
    Anchored on the nominal level of the prompt, not on any R18 output. This is
    the same reading v87 L278 and L290 report, at 1000 streams per penalty
    instead of 30.
    """
    for row in applied.itertuples(index=False):
        lo, hi = wilson_by_score_roots(int(round(row.lb_reject_rate * row.n_streams)),
                                       int(row.n_streams))
        assert abs(lo - row.lb_wilson_low) < 1e-12 and abs(hi - row.lb_wilson_high) < 1e-12
    covered = sum(int(row.lb_wilson_low <= NOMINAL_LEVEL <= row.lb_wilson_high)
                  for row in applied.itertuples(index=False))
    # 33 simultaneous 95% intervals miss at least once with probability
    # 1 - 0.95^33 = 0.816, so "none misses" is not a criterion (preamble S4bis).
    # The criterion is the count, against the 0.999 quantile of the binomial law
    # the misses follow under coverage -- computed here, never typed, so the
    # threshold cannot be read off the observation it judges.
    max_misses = int(stats.binom.ppf(0.999, len(applied), 1.0 - 0.95))
    assert len(applied) - covered <= max_misses, (
        f"{len(applied) - covered} of {len(applied)} per-penalty Wilson intervals miss the nominal "
        f"level, against {max_misses} at the 0.999 quantile of Binomial({len(applied)}, 0.05); "
        f"under coverage the expected number of misses is {0.05 * len(applied):.1f}")


