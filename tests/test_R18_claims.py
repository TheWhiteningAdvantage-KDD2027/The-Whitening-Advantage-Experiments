def test_R18_the_detectable_amplitude_solves_its_own_analytic_equation(amplitude):
    quantile = chi2_quantile_95(LB_LAGS)
    for row in amplitude.itertuples(index=False):
        expected = theta_at_power(POWER_TARGET, int(row.n_steps), quantile)
        assert abs(row.theta_80_analytic / expected - 1.0) < 1e-9, (
            f"theta_80 at n = {row.n_steps}: {row.theta_80_analytic} against {expected} by an "
            f"independent brentq on the explicit geometric sum")
        assert abs(row.rho_80_analytic - 2.0 * row.theta_80_analytic) < 1e-15
        assert abs(row.rho_80_grid - 2.0 * row.theta_80_grid) < 1e-15
        assert row.ci_low <= row.theta_80_grid <= row.ci_high, (
            f"the cluster-bootstrap interval [{row.ci_low}, {row.ci_high}] does not contain the "
            f"point estimate {row.theta_80_grid} at n = {row.n_steps}")


def test_R18_the_detectable_amplitude_halves_when_the_horizon_quadruples(amplitude):
    """
    The n^{-1/2} law, asserted on the ANALYTIC column: ncp is proportional to
    n * theta^2 to first order, so equal power at four times the horizon needs
    half the amplitude. The k >= 2 terms of the geometric sum break it at order
    2*theta^2, which is what HALVING_TOLERANCE prices.
    """
    frame = amplitude.sort_values('n_steps')
    values = np.array(frame['theta_80_analytic'].values, dtype=float)
    for i in range(1, len(values)):
        ratio = values[i] / values[i - 1]
        assert abs(ratio - 0.5) < HALVING_TOLERANCE * 0.5, (
            f"theta_80 moves by a factor {ratio:.4f} from n = {frame['n_steps'].values[i - 1]} "
            f"to {frame['n_steps'].values[i]}, where the first-order law gives 0.5")


def test_R18_the_non_centrality_at_eighty_percent_power_is_a_constant_of_the_test(amplitude):
    """
    ncp at the target power depends on the number of lags and on the level, not
    on the horizon: it is the root of P(chi2_nc(20, ncp) > q) = 0.80. That is why
    theta_80 is an n^{-1/2} law rather than an empirical regularity.
    """
    quantile = chi2_quantile_95(LB_LAGS)
    expected = brentq(lambda ncp: stats.ncx2.sf(quantile, LB_LAGS, ncp) - POWER_TARGET,
                      1e-9, 500.0, xtol=1e-12, rtol=8.9e-16)
    for row in amplitude.itertuples(index=False):
        observed = ncp_by_explicit_sum(row.theta_80_analytic, int(row.n_steps))
        assert abs(observed / expected - 1.0) < 1e-6, (
            f"ncp at 80% power and n = {row.n_steps} is {observed}, against the horizon-free "
            f"root {expected}")


