"""
R18 -- power of the Ljung-Box test on a binary stream. Acceptance and reporting.

Two kinds of statement live in this file and they are kept apart deliberately.

*Blocking assertions* rest on deterministic relations -- the algebra of the
non-centrality parameter, the chi-square quantile, the arithmetic of a Wilson
interval, the closed form of the GARCH penalty and its attainable floor, the
Kish design effect, the Kolmogorov limit law -- or on constants the R18 prompt
and v87 fix. NONE rests on a value R18 produced.

*Reporting output* prints the bound R18 establishes and asserts nothing.

R18 REPRODUCES NO NUMBER OF v87, so there is no regenerated-versus-published
comparison to make. The admissible anchors are therefore the test configuration
the prompt imposes (n = 8000, lag 20, 1000 streams, level 0.05, the four R02c
horizons), the constants of the processes the application arms borrow from R06
and R11 (alpha = 0.08, nu = 7, the two Gamma grids), and the analytic power
expression itself, which is a mathematical statement and not an observation.

The derived rules of this experiment -- the Wilson interval, the non-centrality
of the limiting chi-square, the 0.95 chi-square quantile, the design effect, the
Kolmogorov survival function -- are reimplemented here independently of the
experiment module, so that a test of any of them compares two implementations
rather than restating one.

THE SELF-INVALIDATING ASSERTION. `test_R18_the_measured_sign_streams_sit_below
_the_detectable_amplitude` recomputes rho_80 from the analytic expression and
requires every measured lag-1 autocorrelation of both application arms to lie
below it. That is the sentence docs/sections/R18.md is written around. If a
later campaign, a later river or a later horizon moves a measured
autocorrelation above rho_80, this test fires and the PROSE must be revised --
the bound is not to be widened to accommodate the measurement.
"""

