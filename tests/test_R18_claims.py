def test_R18_the_reported_detectable_amplitude_is_the_one_the_analytic_law_gives(macros):
    """
    Self-invalidating in the other direction: if the instrument later turns out
    sharper or blunter than the macro states, this fires and the prose must
    follow the measurement rather than the measurement the prose.
    """
    quantile = chi2_quantile_95(LB_LAGS)
    theta_80 = theta_at_power(POWER_TARGET, N_STEPS, quantile)
    rho_80 = 2.0 * theta_80
    printed = float(macros['REighteenRhoEighty'])
    # The budget is derived from the mechanism and from the ANALYTIC curve, not
    # from anything R18 measured. The standard error of a proportion at p = 0.80
    # over 1000 streams is sqrt(0.8*0.2/1000); the analytic power curve has a
    # finite slope at its own 0.80 crossing, so that error displaces the crossing
    # by se / slope in theta and twice that in rho. Three of those absorbs the
    # sqrt(design effect) = 1.4 inflation the common-random-numbers design
    # imposes on a functional of the whole curve, and still leaves 2.1 effective
    # standard errors.
    h = 1e-7
    slope = ((analytic_power(theta_80 + h, N_STEPS, quantile)
              - analytic_power(theta_80 - h, N_STEPS, quantile)) / (2.0 * h))
    se_rho = 2.0 * math.sqrt(POWER_TARGET * (1.0 - POWER_TARGET) / N_STREAMS) / slope
    assert abs(printed - rho_80) < 3.0 * se_rho, (
        f"the macro prints rho_80 = {printed} where the analytic law gives {rho_80:.6f}, a gap of "
        f"{abs(printed - rho_80) / se_rho:.2f} standard errors")


