def chi2_quantile_95(df):
    """
    0.95 quantile of the central chi-square, by inverting its survival function
    with brentq rather than by calling `ppf`. Two routes to one number.
    """
    return brentq(lambda q: stats.chi2.sf(q, df) - 0.05, 1e-6, 1e4, xtol=1e-13, rtol=8.9e-16)


def ncp_by_explicit_sum(theta, n, lags=LB_LAGS):
    """
    ncp = n * sum_{k=1..m} rho(k)^2 with rho(k) = (2*theta)^k, accumulated term by
    term. The experiment uses the closed form of the geometric series; this is the
    definition it closes.
    """
    rho = 2.0 * float(theta)
    return float(n) * sum((rho ** k) ** 2 for k in range(1, lags + 1))


def wilson_by_score_roots(k, n, z=1.959963984540054):
    """
    Wilson interval as the two roots of the score equation
    (p_hat - p)^2 = z^2 * p * (1 - p) / n, solved by the quadratic formula.

    The experiment carries R02's centre-and-margin form. Both invert the same
    test; writing it as a quadratic is the independent route.
    """
    if n == 0:
        return 0.0, 0.0
    p_hat = k / n
    a = 1.0 + z * z / n
    b = -(2.0 * p_hat + z * z / n)
    c = p_hat * p_hat
    disc = b * b - 4.0 * a * c
    disc = max(disc, 0.0)
    lo = (-b - math.sqrt(disc)) / (2.0 * a)
    hi = (-b + math.sqrt(disc)) / (2.0 * a)
    return max(0.0, lo), min(1.0, hi)


def gamma_closed_form(alpha, beta):
    """
    The GARCH penalty in closed form. Written from the relation itself rather
    than carried from any experiment, so the CSV's `gamma_realised` is compared
    against a second implementation.
    """
    if alpha == 0.0 and beta == 0.0:
        return 1.0
    phi = alpha + beta
    denom = 1.0 - 2.0 * alpha * beta - beta ** 2
    if denom <= 0.0 or phi >= 1.0:
        return float('inf')
    rho1 = alpha * (1.0 - beta * phi) / denom
    return 1.0 + 2.0 * rho1 / (1.0 - phi)


def kolmogorov_sf(statistic, n, terms=100):
    """
    Asymptotic Kolmogorov survival function,
    Q(lambda) = 2 * sum_{k>=1} (-1)^{k-1} exp(-2 k^2 lambda^2), lambda = sqrt(n)*D.
    Independent of scipy's exact Durbin recursion, up to the O(n^{-1/2}) term the
    tolerance above prices.
    """
    lam = math.sqrt(n) * statistic
    if lam <= 0.0:
        return 1.0
    total = 2.0 * sum((-1) ** (k - 1) * math.exp(-2.0 * k * k * lam * lam)
                      for k in range(1, terms + 1))
    return min(1.0, max(0.0, total))


def theta_at_power(target, n, quantile, lags=LB_LAGS):
    """Root of the analytic power expression, by brentq. The deliverable."""
    def f(theta):
        ncp = ncp_by_explicit_sum(theta, n, lags)
        power = stats.chi2.sf(quantile, lags) if ncp == 0.0 else stats.ncx2.sf(quantile, lags, ncp)
        return power - target
    return brentq(f, 1e-9, 0.25, xtol=1e-15, rtol=8.9e-16)


def analytic_power(theta, n, quantile, lags=LB_LAGS):
    ncp = ncp_by_explicit_sum(theta, n, lags)
    if ncp == 0.0:
        return float(stats.chi2.sf(quantile, lags))
    return float(stats.ncx2.sf(quantile, lags, ncp))


def expected_theta_grid():
    n_geom = THETA_POINTS_PER_DECADE * THETA_GRID_DECADES + 1
    geometric = THETA_GRID_MIN * 10.0 ** (np.arange(n_geom) / THETA_POINTS_PER_DECADE)
    return np.array(sorted(set([0.0]) | set(float(v) for v in geometric) | set(THETA_ANCHORS)))


def kish_design_effect(matrix):
    """Kish design effect, reimplemented from the ratio of variances."""
    p = float(matrix.mean())
    se_cluster = float(np.std(matrix.mean(axis=1), ddof=1) / math.sqrt(matrix.shape[0]))
    se_srs = math.sqrt(p * (1.0 - p) / matrix.size)
    return (se_cluster / se_srs) ** 2


