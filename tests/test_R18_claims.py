def test_R18_the_analytic_power_column_is_the_non_central_chi_square_tail(power_horizon):
    quantile = chi2_quantile_95(LB_LAGS)
    assert abs(quantile - stats.chi2.ppf(0.95, LB_LAGS)) < 1e-9, (
        "the 0.95 chi-square quantile disagrees between inversion by brentq and `ppf`")
    for row in power_horizon.itertuples(index=False):
        expected = analytic_power(row.theta, row.n_steps, quantile)
