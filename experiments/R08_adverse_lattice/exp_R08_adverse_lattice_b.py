def panel_a_whiteness(ax, adverse):
    """
    Panel (A). Both arms' Ljung-Box rejection against b, the gap between them
    annotated in points, and the values of b at which the two-sample proportion
    test rejects marked distinctly.

    The proportion test is the witness's own instrument and it is drawn here as
    a MARKER and not as a verdict: six simultaneous tests at the 5% level reject
    at least once with probability 26.49% under equality itself, which
    `exp_R08_adverse_lattice_a.py` logs before any of them is read.
    """
    grid = adverse['b'].to_numpy(dtype=float)
    biased = adverse['lb_reject_biased'].to_numpy(dtype=float)
    naive = adverse['lb_reject_naive_ref'].to_numpy(dtype=float)
    err_low = np.maximum(0.0, biased - adverse['lb_ci_low'].to_numpy(dtype=float))
    err_high = np.maximum(0.0, adverse['lb_ci_high'].to_numpy(dtype=float) - biased)
    ax.errorbar(grid, biased, yerr=[err_low, err_high], fmt='-o', color=COLOUR_BIASED,
                capsize=4, label=LABEL_BIASED)
    ax.plot(grid, naive, '--s', color=COLOUR_NAIVE, alpha=0.8, label=LABEL_NAIVE)
    rejecting = adverse['pval_lb'].to_numpy(dtype=float) < campaign_module.LB_LEVEL
    if rejecting.any():
        ax.plot(grid[rejecting], biased[rejecting], marker='x', markersize=14, linestyle='none',
                color='black', markeredgewidth=2,
                label=r'proportion test rejects at $5\%$')
    gaps = 100.0 * np.abs(adverse['delta_lb_pp'].to_numpy(dtype=float))
    for position, value, gap in zip(grid, np.maximum(biased, naive), gaps):
        ax.annotate(f"{gap:.2f} pt", xy=(position, value), xytext=(0, 9),
                    textcoords='offset points', ha='center', fontsize=8)
    ax.set_yscale('log')
    ax.set_ylim(0.03, 2.0)
    ax.set_xticks(grid)
    ax.set_yticks([0.05, 0.1, 0.2, 0.3, 0.5, 0.8, 1.0])
    ax.get_yaxis().set_major_formatter(ticker.ScalarFormatter())
    ax.get_yaxis().set_minor_formatter(ticker.NullFormatter())
    ax.set_xlabel(r'Systematic mis-centering magnitude $b$')
    ax.set_ylabel('Ljung-Box rejection rate')
    ax.grid(True, which='both', alpha=0.3)
    ax.legend(loc='lower right', frameon=False, fontsize=8)
    ax.set_title("(A) Whiteness loss is symmetric in the sign of the mis-centering",
                 fontweight="bold", loc="center")


def panel_b_false_alarm(ax, adverse, level_strict, level_weak, star_value):
    """
    Panel (B). Both arms' false-alarm rate against b, read against the two
    levels the two OPERATORS deliver at lambda* and never against the 5% the
    lattice does not attain.

    The delivered script draws `axhline(0.05)` on this panel. That line displays
    a target the lattice makes unattainable, which is the finding panel C
    carries, so it is removed. The prompt asks for the attainable level to be
    drawn in its place; control C1 measures that module A operates at the WEAK
    level and not at the strict one, so BOTH are drawn and each is labelled by
    its operator: the strict level is the one the lattice attains, the weak
    level is the reference against which the b = 0 point is read.
    """
    grid = adverse['b'].to_numpy(dtype=float)
    biased = adverse['fpr_biased'].to_numpy(dtype=float)
    naive = adverse['fpr_naive_ref'].to_numpy(dtype=float)
    err_low = np.maximum(0.0, biased - adverse['fpr_ci_low'].to_numpy(dtype=float))
    err_high = np.maximum(0.0, adverse['fpr_ci_high'].to_numpy(dtype=float) - biased)
    ax.axhspan(min(level_strict, level_weak), max(level_strict, level_weak), color='gray',
               alpha=0.2)
    ax.axhline(level_strict, color='gray', linestyle='--', linewidth=1.2,
               label=(rf'strict $M > \lambda^\star$: {100.0 * level_strict:.2f}%'
                      rf' ($\lambda^\star = {star_value:.1f}$, the level the lattice attains)'))
    ax.axhline(level_weak, color='black', linestyle=':', linewidth=1.5,
               label=(rf'weak $M \geq \lambda^\star$: {100.0 * level_weak:.2f}%'
                      r' (the operator this arm implements)'))
    ax.errorbar(grid, biased, yerr=[err_low, err_high], fmt='-o', color=COLOUR_BIASED,
                capsize=4, label=LABEL_BIASED)
    ax.plot(grid, naive, '--s', color=COLOUR_NAIVE, alpha=0.8, label=LABEL_NAIVE)
    ax.set_ylim(0.0, max(0.22, float(naive.max()) * 1.1))
    ax.set_xticks(grid)
    ax.set_xlabel(r'Systematic mis-centering magnitude $b$')
    ax.set_ylabel('False-alarm rate')
    ax.grid(True, alpha=0.3)
    ax.legend(loc='upper left', frameon=False, fontsize=8)
    ax.set_title("(B) Calibration is not: the sign of the bias sets the direction",
                 fontweight="bold", loc="center")


def panel_c_null_law(ax, units, levels, marked, star_units):
    """
    Panel (C). The survival function of M_H under H0, a step function on
    multiples of 2delta, with the two levels bracketing 5% marked and the
    nominal rule kept HERE ONLY, where it is the legitimate referent.

    The delivered panel plots the six grid points alone. The step function is
    drawn here over the whole scanned lattice region, from the in-memory integer
    statistic, because "step function on multiples of 2delta" is what the
    caption states and six points do not exhibit it.
    """
    values = np.asarray([units_value * campaign_module.LATTICE_UNIT for units_value in units],
                        dtype=float)
    survival = np.asarray(levels, dtype=float)
    ax.step(values, survival, where='post', color='black', linewidth=1.5,
            label=r'$P(M_H > \lambda)$, $2\times 10^5$ fair-coin streams')
    ax.plot(values, survival, 'ko', markersize=3)
    ax.axhline(campaign_module.NOMINAL_LEVEL, color='gray', linestyle=':',
               label=r'nominal $5\%$')
    marked_values = np.asarray([item[0] * campaign_module.LATTICE_UNIT for item in marked],
                               dtype=float)
    marked_levels = np.asarray([item[1] for item in marked], dtype=float)
    ax.plot(marked_values, marked_levels, 'ro', markersize=9,
            label=r'the two attainable levels bracketing $5\%$')
    for units_value, level_value in marked:
        offset = (-78, 16) if units_value == star_units - 1 else (14, -30)
        ax.annotate(rf'$\lambda = {units_value * campaign_module.LATTICE_UNIT:.1f}$'
                    f'\n{100.0 * level_value:.2f}% (strict)',
                    xy=(units_value * campaign_module.LATTICE_UNIT, level_value),
                    xytext=offset, textcoords='offset points', fontsize=8, color='darkred')
    ax.set_yscale('log')
    ax.set_xlabel(r'Critical value $\lambda$ (multiples of $2\delta = 0.2$)')
    ax.set_ylabel(r'Empirical survival probability $P(M_H > \lambda)$')
    ax.grid(True, which='both', alpha=0.3)
    ax.legend(loc='upper right', frameon=False, fontsize=8)
    ax.set_title(r"(C) The null law is discrete: $M_H$ lives on a $2\delta$ lattice",
                 fontweight="bold", loc="center")


def render_figure(campaign, path, logger):
    """v87 Figure 8, three panels, drawn from the in-memory campaign."""
    adverse = campaign['adverse_bias']
    star_units = campaign['star_units']
    star_cell = campaign['measured'][star_units]
    units = list(campaign_module.LATTICE_SCAN_UNITS)
    levels = []
    for units_value in units:
        cell = campaign_module.operator_levels_at(campaign['m_float'], campaign['m_units'],
                                                  units_value,
                                                  units_value * campaign_module.LATTICE_UNIT)
        levels.append(cell['level_strict'])
    marked = [(star_units - 1, campaign['measured'][star_units - 1]['level_strict']),
              (star_units, star_cell['level_strict'])]

    fig, axes = plt.subplots(1, 3, figsize=(19, 5.5), dpi=300)
    panel_a_whiteness(axes[0], adverse)
    panel_b_false_alarm(axes[1], adverse, star_cell['level_strict'], star_cell['level_weak'],
                        campaign['lambda_star'])
    panel_c_null_law(axes[2], units, levels, marked, star_units)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    logger.info(f"Figure 8 written to {path.name}. Panel (A) both arms' Ljung-Box rejection on a "
                f"log ordinate with the gap annotated in points and the proportion-test "
                f"rejections marked. Panel (B) both arms' false-alarm rate with the 5% rule "
                f"REMOVED and the two operator levels drawn in its place -- strict "
                f"{100.0 * star_cell['level_strict']:.4f}% and weak "
                f"{100.0 * star_cell['level_weak']:.4f}% at lambda* = "
                f"{campaign['lambda_star']!r} -- with the band between them shaded and each line "
                f"labelled by its operator. Panel (C) the survival function over the "
                f"{len(units)} scanned lattice points as a step function on multiples of "
                f"{campaign_module.LATTICE_UNIT}, the two bracketing levels marked, and the 5% "
                f"rule kept here only. Cosmetic divergence from the submitted "
                f"Fig26_Adverse_Bias_and_Lattice.png, declared per the protocol: bold horizontally "
                f"centred panel titles prefixed (A)-(C). The removal of the 5% rule from panels "
                f"(A) and (B) is NOT cosmetic and is recorded in docs/audits/AUDIT_R08.md.")


