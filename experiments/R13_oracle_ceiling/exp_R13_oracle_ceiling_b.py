MACRO_HEADER = "% Auto-generated by exp_R13_oracle_ceiling_b.py -- do not edit."
FIGURE_ORACLE = "V1"
FIGURE_EPISODES = ("E1", "E2", "E3", "E4")
PANEL_LETTERS = ("A", "B", "C", "D")
# The three curves of Figure 14, in the caption's own order.
CURVE_LR = "D2 (likelihood-ratio)"
CURVE_DELTA_ZERO = r"D1 (standardized-mean, $\delta = 0$)"
CURVE_DELTA_OPT = r"D1 (standardized-mean, $\delta = \delta_{\mathrm{opt}}$)"


def plot_curve(ax, frame, label, colour, style):
    """
    One frontier curve, sorted on lambda so that the polyline follows the
    threshold sweep rather than the row order, and restricted to thresholds the
    realized path actually crossed.
    """
    sub = frame.sort_values('lambda').dropna(subset=['tau_realized_days'])
    if sub.empty:
        return False
    ax.plot(sub['FPR_H'], sub['tau_realized_days'], label=label, color=colour,
            linestyle=style, linewidth=2)
    return True


def render_figure(frontier, diagnostics, path, logger):
    """
    v87 Figure 14, four panels, drawn from the in-memory campaign.

    Cosmetic divergence from the submitted PNG, declared per preamble S6: the
    panel titles are bold, left-aligned and prefixed `(A)`-`(D)`, and the legend
    names the detector FAMILY rather than the label. No numerical value moves.
    """
    frame_v1 = frontier[(frontier['sigma_oracle'] == FIGURE_ORACLE)
                        & (~frontier['oracle_contaminated'])]
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    axes = axes.flatten()
    for i, episode in enumerate(FIGURE_EPISODES):
        ax = axes[i]
        frame_ep = frame_v1[frame_v1['episode_id'] == episode]
        if frame_ep.empty:
            logger.error(f"Figure 14: episode {episode} has no {FIGURE_ORACLE} row.")
            sys.exit(1)
        t_days = int(frame_ep['T_days_phase'].iloc[0])
        ticker = frame_ep['ticker'].iloc[0]
        phase = int(frame_ep['phase_id'].iloc[0])
        # delta_opt comes from the diagnostics value the campaign computed, not
        # from a search for the delta that is absent from the static grid.
        d_opt = float(diagnostics[(diagnostics['episode_id'] == episode)
                                  & (diagnostics['sigma_oracle'] == FIGURE_ORACLE)
                                  ].iloc[0]['delta_opt'])
        drawn = []
        if plot_curve(ax, frame_ep[frame_ep['detector'] == 'D2'], CURVE_LR, 'black', '-'):
            drawn.append('D2')
        d1 = frame_ep[frame_ep['detector'] == 'D1']
        zero = d1[np.isclose(d1['delta'].to_numpy(dtype=float), 0.0, rtol=0.0, atol=0.0)]
        if plot_curve(ax, zero, CURVE_DELTA_ZERO, 'tab:blue', '--'):
            drawn.append('D1 delta=0')
        opt = d1[np.isclose(d1['delta'].to_numpy(dtype=float), d_opt, rtol=0.0, atol=0.0)]
        if opt.empty:
            logger.error(f"Figure 14: episode {episode} carries no D1 row at delta_opt = "
                         f"{d_opt!r}.")
            sys.exit(1)
        if plot_curve(ax, opt, CURVE_DELTA_OPT, 'tab:orange', '-.'):
            drawn.append('D1 delta_opt')
        ax.axhline(t_days, color='tab:red', linestyle=':', linewidth=2,
                   label=r'Phase end ($T$)')
        ax.set_xscale('log')
        ax.set_xlim(1e-3, 1.0)
        ax.invert_xaxis()
        ax.set_title(f"({PANEL_LETTERS[i]}) {episode} -- {ticker} phase {phase}, $T = {t_days}$ d",
                     fontweight="bold", loc="center")
        ax.set_xlabel(r"Bootstrap false-alarm probability $\mathrm{FPR}_H$ [reversed log scale]")
        ax.set_ylabel(r"Realized detection delay $\tau$ (trading days)")
        ax.legend(loc="upper left" if i < 2 else "lower right", fontsize=9)
        ax.grid(True, which="both", ls="-", alpha=0.2)
        logger.info(f"Figure 14 panel ({PANEL_LETTERS[i]}) {episode}: {ticker} phase {phase}, "
                    f"T = {t_days} d, delta_opt = {d_opt!r}, curves drawn {drawn}.")
    fig.suptitle("Empirical oracle detectability frontier "
                 "(look-ahead GARCH parameters, causal filtration)",
                 fontweight='bold', fontsize=14, ha='center')
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)
    logger.info(f"Figure 14 written to {path.name}: {FIGURE_ORACLE} only, three curves per panel "
                f"(likelihood-ratio; standardized-mean at delta = 0 and at delta_opt), dotted "
                f"phase-end rule. Cosmetic divergence from the submitted PNG, per preamble S6: "
                f"bold horizontally centred panel titles prefixed (A)-(D). No numerical value "
                f"moves on that account.")


def episode_verdict(operating_points, diagnostics, episode):
    """
    The verdict of the standardized-mean CUSUM at the matched operating point,
    at the two settings v87's Figure 14 caption names.

    The macro body is `<verdict at delta = 0> / <verdict at delta_opt>` because
    the two settings do not always agree, and a single word would hide which one
    the reader is being given.
    """
    sub = operating_points[
        (operating_points['episode_id'] == episode)
        & (operating_points['sigma_oracle'] == FIGURE_ORACLE)
        & (operating_points['detector'] == 'D1')
        & (operating_points['operating_point'] == campaign_module.MATCHED_OPERATING_POINT)]
    d_opt = float(diagnostics[(diagnostics['episode_id'] == episode)
                              & (diagnostics['sigma_oracle'] == FIGURE_ORACLE)
                              ].iloc[0]['delta_opt'])
    words = {'detected_within_T': 'detected', 'alarm_beyond_T': 'alarm beyond $T$',
             'no_alarm': 'no alarm', 'not_attainable': 'operating point not attainable'}
    zero = sub[np.isclose(sub['delta'].to_numpy(dtype=float), 0.0, rtol=0.0, atol=0.0)].iloc[0]
    opt = sub[np.isclose(sub['delta'].to_numpy(dtype=float), d_opt, rtol=0.0, atol=0.0)].iloc[0]
    return f"{words[zero['oracle_verdict']]} / {words[opt['oracle_verdict']]}", zero, opt, d_opt


def main():
    parser = argparse.ArgumentParser(
        description="R13 (b) -- Figure 14 and the claims of v87 L331")
    parser.add_argument("--n-jobs", type=int, default=len(campaign_module.EPISODES),
                        help="Worker processes for the campaign this stage re-runs in memory.")
    args = parser.parse_args()

    RESULTS_DIR = BASE_DIR / "results" / "R13_oracle_ceiling"
    DATA_DIR = RESULTS_DIR / "data"
    FIGURES_DIR = RESULTS_DIR / "figures"
    TABLES_DIR = RESULTS_DIR / "tables"
    LOGS_DIR = BASE_DIR / "logs" / "R13_oracle_ceiling"
    for d in (DATA_DIR, FIGURES_DIR, TABLES_DIR, LOGS_DIR):
        d.mkdir(parents=True, exist_ok=True)

    logger = setup_logging(LOGS_DIR / "exp_R13_oracle_ceiling_b.log", "exp_R13_oracle_ceiling_b")
    if not verify_hash_seed(logger):
        sys.exit(1)
    log_environment(logger, ["numpy", "pandas", "scipy", "statsmodels", "matplotlib", "pytest"])
    log_artifact_manifest(logger, [], BASE_DIR / "experiments" / "R13_oracle_ceiling", BASE_DIR)
    t0 = time.time()

    logger.info("R13 (b) renders v87 Figure 14 (fig:oracle_frontier) and emits the macros of "
                "L331. The campaign is RE-RUN in memory rather than reloaded from CSV: preamble "
                "S7 forbids a disk round trip as a memory bridge, so the figure and every macro "
                "below are computed from the objects exp_R13_oracle_ceiling_a.run_campaign "
                "returns.")

    campaign_module.check_source_identity(logger)
    campaign = campaign_module.run_campaign(logger, args.n_jobs)

    frontier = campaign['frontier']
    operating_points = campaign['operating_points']
    diagnostics = campaign['diagnostics']

    published_rows = campaign_module.control_c1(campaign, logger)
    covid_lr = published_rows['covid_lr']
    covid_std_mean = published_rows['covid_std_mean']
    jensen = published_rows['jensen']

    render_figure(frontier, diagnostics, FIGURES_DIR / "fig14_oracle_frontier.png", logger)

    # =====================================================================
    # LATEX MACROS
    # =====================================================================
    # Cardinal, not ordinal: preamble S6 fixes \R<Ordinal><Claim> with the
    # ordinal in English words, and the repository realises cardinals throughout
    # (ROne ... RSix, REleven, RSixteen, REighteen). Every value below is
    # computed from an object in memory; no literal is typed.
    delay_lr = int(covid_lr['tau_realized_days'])
    fpr_lr = float(covid_lr['FPR_H'])
    delay_std_mean = int(covid_std_mean['tau_realized_days'])
    jensen_ratio = float(jensen['jensen_ratio'])
    jensen_oracle = str(jensen['sigma_oracle'])
    n_certified = int(operating_points['oracle_certified'].sum())
    n_contaminated = int(operating_points['oracle_contaminated'].sum())
    arl0_censored_frac = float(covid_lr['arl0_censored_frac'])

    available = frontier[frontier['ARL0'].notna()]
    logger.info(f"\\RThirteenArlZeroCensoredFrac is bound to the censored fraction of the "
                f"PUBLISHED row -- E1 / D2 / V1 / "
                f"{campaign_module.PUBLISHED_OPERATING_POINT} -- which is "
                f"{arl0_censored_frac!r}. The campaign-wide distribution over the "
                f"{len(available)} rows whose ARL0 survived the "
                f"{campaign_module.ARL0_CENSOR_THRESHOLD:.0%} censoring rule is: min "
                f"{float(available['arl0_censored_frac'].min())!r}, median "
                f"{float(available['arl0_censored_frac'].median())!r}, mean "
                f"{float(available['arl0_censored_frac'].mean())!r}, max "
                f"{float(available['arl0_censored_frac'].max())!r}. Over ALL "
                f"{int(frontier['arl0_available'].sum())} rows where the ARL0 null was run, "
                f"including the suppressed ones, the mean censored fraction is "
                f"{float(frontier[frontier['arl0_available']]['arl0_censored_frac'].mean())!r}.")

    verdicts = {}
    for episode in FIGURE_EPISODES:
        body, zero, opt, d_opt = episode_verdict(operating_points, diagnostics, episode)
        verdicts[episode] = body
        logger.info(f"Verdict macro for {episode} [{zero['role']}] at "
                    f"{campaign_module.MATCHED_OPERATING_POINT} on {FIGURE_ORACLE}: "
                    f"delta = 0 -> {zero['oracle_verdict']} (FPR_H = {zero['FPR_H']!r}, tau = "
                    f"{zero['tau_realized_days']!r}), delta_opt = {d_opt!r} -> "
                    f"{opt['oracle_verdict']} (FPR_H = {opt['FPR_H']!r}, tau = "
                    f"{opt['tau_realized_days']!r}). Macro body: \"{body}\".")

    macros = [
        MACRO_HEADER,
        "% THE OPERATING POINT BEHIND EVERY MACRO, NAMED, because v87 L331 does not name either.",
        f"% \\RThirteenCovidDelayLR, \\RThirteenCovidFprLR, \\RThirteenCovidDelayStdMean and",
        f"%   \\RThirteenArlZeroCensoredFrac are read at {campaign_module.PUBLISHED_OPERATING_POINT}",
        "%   -- the first threshold whose bootstrap ARL0 reaches 252, i.e. one false alarm per",
        "%   trading year, which is the calibration L331's surrounding sentence uses for the sign",
        "%   floor. The first two come from ONE row of R13_oracle_operating_points.csv,",
        "%   E1 / D2 / V1, which control C1 asserts.",
        f"% \\RThirteenCovidVerdict, \\RThirteenRecoveryVerdict, \\RThirteenAdvanceVerdict and",
        f"%   \\RThirteenCorrectionVerdict are read at {campaign_module.MATCHED_OPERATING_POINT}",
        "%   -- bootstrap FPR_H at or below 5% -- which is the DIFFERENT operating point L331",
        "%   calls 'the matched operating point'. Each body is",
        "%   `<verdict at delta = 0> / <verdict at delta_opt>` on the standardized-mean CUSUM,",
        "%   the two settings v87's Figure 14 caption names; the two settings do not always",
        "%   agree and a single word would hide which one the reader is given.",
        "% \\RThirteenJensenRatio and \\RThirteenJensenOracle come from R13_oracle_diagnostics.csv",
        "%   and are specific to ONE oracle of three; the other two are logged beside them.",
        "% NO MACRO NAMES ADD_min OR THE SHARPE CEILING. R16 owns both and R13 cites \\RSixteen...",
        f"\\newcommand{{\\RThirteenCovidDelayLR}}{{{delay_lr}}}",
        f"\\newcommand{{\\RThirteenCovidFprLR}}{{{100.0 * fpr_lr:.1f}\\%}}",
        f"\\newcommand{{\\RThirteenCovidDelayStdMean}}{{{delay_std_mean}}}",
        f"\\newcommand{{\\RThirteenJensenRatio}}{{{jensen_ratio:.1f}}}",
        f"\\newcommand{{\\RThirteenJensenOracle}}{{{jensen_oracle}}}",
        f"\\newcommand{{\\RThirteenOracleCertifiedCount}}{{{n_certified}}}",
        f"\\newcommand{{\\RThirteenOracleContaminatedCount}}{{{n_contaminated}}}",
        f"\\newcommand{{\\RThirteenArlZeroCensoredFrac}}{{{arl0_censored_frac:.4f}}}",
        f"\\newcommand{{\\RThirteenCovidVerdict}}{{{verdicts['E1']}}}",
        f"\\newcommand{{\\RThirteenRecoveryVerdict}}{{{verdicts['E2']}}}",
        f"\\newcommand{{\\RThirteenAdvanceVerdict}}{{{verdicts['E3']}}}",
        f"\\newcommand{{\\RThirteenCorrectionVerdict}}{{{verdicts['E4']}}}",
    ]

    tex_path = TABLES_DIR / "R13_claims.tex"
    with open(tex_path, "w") as handle:
        handle.write("\n".join(macros) + "\n")
    n_emitted = sum(1 for m in macros if m.startswith("\\newcommand"))
    undefined = [m for m in macros if m.startswith("\\newcommand") and 'nan' in m.lower()]
    if undefined:
        logger.error(f"{len(undefined)} macros carry the body `nan`: {undefined}")
        sys.exit(1)
    logger.info(f"Emitted {n_emitted} macros to {tex_path.name}, prefix \\RThirteen per preamble "
                f"S6's ordinal-in-English rule; \\RThirteenth appears nowhere. Every value is "
                f"computed from an object in memory. No macro names ADD_min or the Sharpe "
                f"ceiling: R16 owns both.")

    # =====================================================================
    # THE CAMPAIGN AS `_a` PERSISTED IT, RE-DIGESTED
    # =====================================================================
    # `_b` re-runs the campaign; if the two runs differed, the figure and the
    # macros would describe a campaign the CSVs do not contain. The digests are
    # recomputed here from the in-memory frames and compared with the files.
    artefacts = {
        "R13_oracle_frontier.csv": frontier,
        "R13_oracle_operating_points.csv": operating_points,
        "R13_oracle_diagnostics.csv": diagnostics,
        "R13_clairvoyant_floor.csv": campaign['clairvoyant_floor'],
        "R13_detector_recovery.csv": campaign['detector_recovery'],
        "R13_qmle_recovery.csv": campaign['qmle_recovery'],
    }
    mismatched = []
    with tempfile.TemporaryDirectory() as scratch_dir:
        scratch = Path(scratch_dir) / "reconciliation.csv"
        for name, frame in artefacts.items():
            persisted = DATA_DIR / name
            if not persisted.exists():
                logger.error(f"Missing input: {persisted}. Run exp_R13_oracle_ceiling_a.py first.")
                sys.exit(1)
            save_fair_csv(frame, scratch)
            if compute_sha256(scratch) != compute_sha256(persisted):
                mismatched.append(name)
            logger.info(f"SHA-256 {name:<36} : {compute_sha256(persisted)}")
    if mismatched:
        logger.error(f"The campaign this stage re-ran differs from the one _a persisted on "
                     f"{mismatched}. The figure and the macros would describe a campaign the CSVs "
                     f"do not contain.")
        sys.exit(1)
    logger.info(f"Re-run reconciliation: all {len(artefacts)} CSVs re-serialise to the digests "
                f"exp_R13_oracle_ceiling_a wrote. The figure and the macros describe the persisted "
                f"campaign.")

    logger.info(f"SHA-256 {'fig14_oracle_frontier.png':<36} : "
                f"{compute_sha256(FIGURES_DIR / 'fig14_oracle_frontier.png')}")
    logger.info(f"SHA-256 {tex_path.name:<36} : {compute_sha256(tex_path)}")
    logger.info(f"Execution completed in {time.time() - t0:.1f}s.")


if __name__ == "__main__":
    main()
