#!/usr/bin/env python3
"""
==========================================================================
R13 (b) -- FIGURE 14 AND THE CLAIMS OF v87 L331
==========================================================================
Second stage of the R13 chain. `_a` runs the campaign and writes the six CSVs;
this script renders `fig:oracle_frontier` and emits the LaTeX macros.

WHY THE CAMPAIGN IS RE-RUN RATHER THAN RELOADED. Preamble S7 and SPECS 1.6
forbid using a CSV as a memory bridge: a figure re-plotted from a reloaded CSV,
or a macro computed from one, reads values that have been through a decimal
round trip. `run_campaign` is imported from `_a` and called again, and every
value below is taken from the objects it returns in RAM. The campaign is
deterministic, so the frames this script holds are the frames `_a` persisted;
the digests printed at the end are the check on that, not an assumption.

THE FIGURE. Four panels, one per episode, `V1` only -- the certified parametric
oracle -- with three curves: the likelihood-ratio CUSUM (`D2`), and the
standardized-mean CUSUM (`D1`) at `delta = 0` and at `delta_opt`, which are the
two settings v87's caption names. The horizontal axis is `FPR_H` on a reversed
log scale, so that reading left to right is reading toward stricter
calibration; the dotted rule is the phase end `T`. `delta_opt` is taken from the
in-memory diagnostics value, never from the delivered plotting script's
"the delta that is not on the static grid" heuristic, which would silently pick
the wrong curve the day `delta_opt` lands on a grid point.

THE MACROS. `\\RThirteenCovidDelayLR` and `\\RThirteenCovidFprLR` are read from
ONE row -- `E1 / D2 / V1 / OP2b_ARL0_252` -- which is what control C1 asserts.
No macro is emitted for `ADD_min` or for the Sharpe ceiling: R16 owns those and
R13 cites `\\RSixteen...`.

NOTATION: see the module docstring of exp_R13_oracle_ceiling_a.py.
==========================================================================
"""

